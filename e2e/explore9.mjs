import { launch, signedInContext, WEB, sleep } from './lib.mjs'
const b = await launch(); const ctx = await signedInContext(b, 'S1'); const page = await ctx.newPage()
const logs = []; page.on('console', m => { if (/error|warn/.test(m.type()) && !/54321|ERR_NAME|ERR_CONN/.test(m.text())) logs.push(m.text().slice(0, 200)) }); page.on('pageerror', e => logs.push('PAGEERROR ' + e.message.slice(0, 200)))
await page.goto(WEB + '/student/courses/C1/assignments/A1/coach', { waitUntil: 'domcontentloaded' }); await sleep(3500)
await page.locator('button:has-text("Whiteboard")').first().click(); await sleep(6500)
await page.locator('button:has-text("Fit to")').first().click(); await sleep(800)
await page.mouse.click(1050, 460); await sleep(900)
const btn = page.locator('button:has-text("Open and run")').first()
console.log('open button visible', await btn.isVisible().catch(() => false), JSON.stringify(await btn.boundingBox().catch(() => null)))
await btn.click({ timeout: 5000 }).catch(e => console.log('CLICK ERR', e.message.split('\n')[0]))
await sleep(2500)
console.log('iframes', (await page.$$('iframe')).length, '| dialogs', await page.$$eval('[role=dialog]', d => d.length))
await page.screenshot({ path: 'evidence/explore-open-and-run.png' })
console.log(logs.slice(0, 5).join('\n')); await b.close()
