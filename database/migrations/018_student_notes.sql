-- 018_student_notes.sql -- a personal notes space for every student, available across classes, conversations and the workspace.
--
-- Additive and forward-only: one new table, no existing table, row, constraint or policy is touched. Reverse with
-- database/migrations/down/018_student_notes.down.sql (drops only this table).
--
-- * public.student_notes: a note belongs to exactly ONE student (composite FK to students(student_id, university_id), the same tenant
--   integrity rule 009 applies to all student-owned rows), is deleted with that student, and is not tied to any course or conversation.
-- * note_id is generated by the CLIENT (note_<32 hex>) so that a retried create can never produce a second note: the insert is idempotent.
-- * version increases on every update: the API uses it for optimistic concurrency (two tabs/devices editing the same note).
-- * source_kind/source_ref record where a note came from ("Save to Notes" on a Coach reply); the partial unique index makes saving the
--   same reply twice impossible, even under concurrent requests.
--
-- RLS: same model as 013. ALL reads and writes go through the backend (service connection, ownership enforced in code). For the Data API
-- surface, RLS is enabled with strict ownership policies for SELECT, INSERT, UPDATE and DELETE (a student only ever matches their own rows),
-- but only SELECT is GRANTed to `authenticated`: the Data API stays read-only, as 013 requires. anon gets nothing.
-- Idempotent: safe to run repeatedly.
BEGIN;

CREATE TABLE IF NOT EXISTS public.student_notes (
  note_id        text PRIMARY KEY CHECK (note_id ~ '^note_[0-9a-f]{32}$'),
  student_id     text NOT NULL,
  university_id  text NOT NULL,
  title          text NOT NULL DEFAULT '' CHECK (char_length(title) <= 200),
  content        text NOT NULL DEFAULT '' CHECK (char_length(content) <= 100000),
  source_kind    text CHECK (source_kind IS NULL OR source_kind IN ('coach_message')),
  source_ref     text CHECK (source_ref IS NULL OR char_length(source_ref) BETWEEN 1 AND 200),
  version        integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT student_notes_student_university_fk FOREIGN KEY (student_id, university_id)
    REFERENCES public.students (student_id, university_id) ON DELETE CASCADE,
  CONSTRAINT student_notes_source_pair_chk CHECK ((source_kind IS NULL) = (source_ref IS NULL))
);

CREATE INDEX IF NOT EXISTS student_notes_student_updated_idx ON public.student_notes (student_id, updated_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS student_notes_source_uidx ON public.student_notes (student_id, source_kind, source_ref)
  WHERE source_ref IS NOT NULL;

DROP TRIGGER IF EXISTS student_notes_set_updated_at ON public.student_notes;
CREATE TRIGGER student_notes_set_updated_at BEFORE UPDATE ON public.student_notes
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.student_notes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.student_notes FROM PUBLIC, anon, authenticated;

DROP POLICY IF EXISTS student_notes_select ON public.student_notes;
DROP POLICY IF EXISTS student_notes_insert ON public.student_notes;
DROP POLICY IF EXISTS student_notes_update ON public.student_notes;
DROP POLICY IF EXISTS student_notes_delete ON public.student_notes;
CREATE POLICY student_notes_select ON public.student_notes FOR SELECT TO authenticated
  USING (student_id = app.current_user_id());
CREATE POLICY student_notes_insert ON public.student_notes FOR INSERT TO authenticated
  WITH CHECK (student_id = app.current_user_id() AND university_id = app.current_university_id());
CREATE POLICY student_notes_update ON public.student_notes FOR UPDATE TO authenticated
  USING (student_id = app.current_user_id())
  WITH CHECK (student_id = app.current_user_id() AND university_id = app.current_university_id());
CREATE POLICY student_notes_delete ON public.student_notes FOR DELETE TO authenticated
  USING (student_id = app.current_user_id());

GRANT SELECT ON public.student_notes TO authenticated;              -- read-only Data API (013); writes go through the backend

COMMIT;
